import { useEffect, useState } from "react";
import { Link, useSearchParams } from "react-router-dom";
import { api, type Comparison, type PrioritizationRow } from "../lib/api";
import { ActionBadge, DataTag, EmptyState, ErrorBox, Loading, PageHeader, Panel, TierBadge } from "../components/ui";
import { FIT_MEANING, INTENT_MEANING, RULE_PLAIN, RejectedRow, SignalRow } from "../components/intel";

const DEFAULT_NAMES = ["Company 36 B2B", "Company 37 Cloud", "Acme Technologies"];

export default function ComparePage() {
  const [params, setParams] = useSearchParams();
  const [rows, setRows] = useState<PrioritizationRow[] | null>(null);
  const [data, setData] = useState<Comparison | null>(null);
  const [error, setError] = useState<string | null>(null);
  const ids = (params.get("ids") ?? "").split(",").map(Number).filter((n) => Number.isInteger(n) && n > 0);

  useEffect(() => {
    api.prioritization().then(setRows).catch((e: unknown) => setError(e instanceof Error ? e.message : String(e)));
  }, []);

  // Default comparison: the API's featured "strong intent vs strong fit" pair plus Acme.
  useEffect(() => {
    if (ids.length >= 2 || !rows) return;
    api.featured().then((f) => {
      const pair = f[0]?.account_ids ?? [];
      const byName = DEFAULT_NAMES.map((n) => rows.find((r) => r.name === n)?.id).filter((x): x is number => !!x);
      const chosen = [...new Set([...pair, ...byName])].slice(0, 3);
      if (chosen.length >= 2) setParams({ ids: chosen.join(",") }, { replace: true });
    }).catch((e: unknown) => setError(e instanceof Error ? e.message : String(e)));
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [rows]);

  const key = ids.join(",");
  useEffect(() => {
    if (ids.length < 2) return;
    setData(null); setError(null);
    api.compare(ids).then(setData).catch((e: unknown) => setError(e instanceof Error ? e.message : String(e)));
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [key]);

  function setSlot(i: number, value: string) {
    const next = [...ids];
    if (value) next[i] = Number(value); else next.splice(i, 1);
    const unique = [...new Set(next.filter(Boolean))].slice(0, 4);
    setParams(unique.length ? { ids: unique.join(",") } : {}, { replace: true });
  }

  const picker = rows && (
    <div className="flex flex-wrap items-end gap-2">
      {[0, 1, 2, 3].slice(0, Math.min(4, Math.max(ids.length + 1, 2))).map((i) => (
        <label key={i} className="min-w-[180px] flex-1 sm:flex-none">
          <span className="label">Account {i + 1}</span>
          <select className="input" value={ids[i] ?? ""} onChange={(e) => setSlot(i, e.target.value)}>
            <option value="">{i < 2 ? "Choose an account" : "Add another (optional)"}</option>
            {rows.map((r) => <option key={r.id} value={r.id} disabled={ids.includes(r.id) && ids[i] !== r.id}>{r.name} · {r.total?.toFixed(1)}</option>)}
          </select>
        </label>
      ))}
    </div>
  );

  return (
    <div className="space-y-4">
      <PageHeader eyebrow="Account intelligence" title="Compare accounts"
        description={<>Same tier does not mean same action. <b className="font-semibold text-ink">Fit</b>: {FIT_MEANING} <b className="font-semibold text-ink">Intent</b>: {INTENT_MEANING}</>} />
      {picker}
      {error && <ErrorBox message={error} />}
      {!error && ids.length < 2 && rows && <EmptyState title="Choose at least two accounts to compare" />}
      {!error && ids.length >= 2 && !data && <Loading label="Comparing" />}
      {data && (
        <>
          <Panel title="What the numbers say">
            <ul className="list-disc space-y-1 pl-5 text-ink-2">{data.observations.map((o, i) => <li key={i}>{o}</li>)}</ul>
            <p className="mt-2 text-2xs text-ink-4">Generated by code from the scores below, not by a language model.</p>
          </Panel>

          <div className="panel overflow-x-auto" tabIndex={0}>
            <table className="tbl min-w-[640px]">
              <thead>
                <tr>
                  <th className="w-40" />
                  {data.accounts.map((a) => (
                    <th key={a.account.id} className="!normal-case !tracking-normal">
                      <Link to={`/app/accounts/${a.account.id}`} className="text-sm font-semibold text-ink hover:text-accent-700 hover:underline">{a.account.name}</Link>
                      {a.includes_synthetic_demo_additions && <div className="mt-1"><DataTag>Synthetic demo note</DataTag></div>}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {([
                  ["Fit", (a) => <><span className="num text-base font-semibold">{a.fit.score.toFixed(1)}</span><span className="text-ink-4"> / 80</span></>],
                  ["Intent", (a) => <><span className="num text-base font-semibold">{a.intent.score.toFixed(1)}</span><span className="text-ink-4"> / 20</span></>],
                  ["Total", (a) => <><span className="num text-base font-semibold">{a.total.total.toFixed(1)}</span><span className="text-ink-4"> / 100</span></>],
                  ["Priority", (a) => <TierBadge tier={a.total.tier} />],
                  ["Recommended action", (a) => <ActionBadge action={a.recommendation.action} />],
                  ["Why (rule)", (a) => <><div className="text-ink-2">{RULE_PLAIN[a.recommendation.rule_id] ?? a.recommendation.reason}</div><div className="mt-1 font-mono text-2xs text-ink-4">{a.recommendation.rule}</div></>],
                  ["Signals counted", (a) => <span className="num">{a.evidence_summary.counted} of {a.evidence_summary.buying_signals}</span>],
                  ["Rejected claims", (a) => <span className="num">{a.evidence_summary.rejected}</span>],
                  ["Disqualifiers", (a) => a.intent.disqualifiers.length ? a.intent.disqualifiers.map((d) => `${d.label} (${d.points.toFixed(0)})`).join(", ") : <span className="text-ink-4">None</span>],
                ] as [string, (a: Comparison["accounts"][number]) => React.ReactNode][]).map(([label, render]) => (
                  <tr key={label}>
                    <th scope="row" className="!static !bg-surface !text-left !text-xs !font-medium !normal-case !tracking-normal !text-ink-3">{label}</th>
                    {data.accounts.map((a) => <td key={a.account.id} className="align-top">{render(a)}</td>)}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          <div className={`grid gap-4 ${data.accounts.length >= 3 ? "lg:grid-cols-3" : "lg:grid-cols-2"}`}>
            {data.accounts.map((a) => (
              <Panel key={a.account.id} title={`Evidence: ${a.account.name}`}>
                <h3 className="eyebrow">Supporting evidence</h3>
                {a.intent.buying_signals.length ? (
                  <ul className="mt-1 divide-y divide-line">{a.intent.buying_signals.map((c) => <SignalRow key={c.signal_id} c={c} e={a} />)}</ul>
                ) : <p className="mt-1 text-ink-3">No verified buying signals.</p>}
                <h3 className="eyebrow mt-4">Rejected evidence</h3>
                {a.rejected_evidence.length ? (
                  <ul className="mt-1 divide-y divide-line">{a.rejected_evidence.map((r, i) => <RejectedRow key={i} r={r} />)}</ul>
                ) : <p className="mt-1 text-ink-3">None.</p>}
              </Panel>
            ))}
          </div>
        </>
      )}
    </div>
  );
}
